-- 2. الفرق بين أوامر الحذف
-- DELETE vs TRUNCATE
-- ==============================================================================
-- يدعم استخدام جملة شرطية مما يتيح لك حذف صف أو عدة صفوف محددة
-- DELETE FROM
-- لا يدعم الجمل الشرطية بل يقوم بحذف جميع السجلات من الجدول دفعة واحدة
-- TRUNCATE
-- لا يقوم بإعادة ضبط العداد التلقائي
-- DELETE FROM
-- يعيد تصفير العداد التلقائي إلى قيمته الابتدائية
-- TRUNCATE
-- يمكن محاكاة الحذف الشامل دون تصفير العداد التلقائي بتجاهل الجملة الشرطية في استعلام
-- DELETE FROM

-- مثال: حذف جميع السجلات مع تصفير العداد التلقائي
