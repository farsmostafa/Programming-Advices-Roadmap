-- 1. الحقل التلقائي
-- AUTO INCREMENT / IDENTITY
-- ==============================================================================
-- الوصف: يسمح هذا الحقل بتوليد رقم فريد تلقائيا عند إدخال سجل جديد في الجدول
-- يفضل استخدامه لإنشاء قيمة فريدة لكل سجل جديد تلقائيا كمفتاح أساسي
-- Primary Key
-- في خوادم مايكروسوفت يتم استخدام الكلمة المفتاحية التالية لتفعيل هذه الخاصية
-- IDENTITY
-- تعني أن التسلسل يبدأ بالرقم 1 ويزداد بمقدار 1 في الصيغة التالية
-- IDENTITY(1,1)
-- لتعديل نقطة البداية إلى 10 ومقدار الزيادة إلى 5 تكتب الصيغة كالتالي
-- IDENTITY(10,5)
-- عند تنفيذ استعلام الإدخال لا نقوم بتمرير أي قيمة لهذا الحقل لأنه يضاف ذاتيا

CREATE TABLE Persons (
    Personid INT IDENTITY(1,1) PRIMARY KEY,
    LastName VARCHAR(255) NOT NULL,
    FirstName VARCHAR(255),
    Age INT
);
