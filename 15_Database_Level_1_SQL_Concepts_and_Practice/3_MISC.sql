-- ==============================================================================
-- 3. المفتاح الأجنبي
-- FOREIGN KEY
-- ==============================================================================
-- يستخدم هذا القيد لإنشاء علاقة ترابط بين جدولين مختلفين
-- يضمن أن قيمة المفتاح الأجنبي في الجدول الفرعي تمتلك قيمة مطابقة في الجدول الأساسي
-- من الممارسات العامة ربط المفتاح الأجنبي بالمفتاح الأساسي للجدول الأب
-- Primary Key

-- إعداد الجدول الأساسي 
CREATE TABLE Customers (
    id INT PRIMARY KEY,
    first_name VARCHAR(40),
    last_name VARCHAR(40),
    age INT,
    country VARCHAR(10)
);
GO

-- الطريقة الأولى: إضافة المفتاح الأجنبي عند إنشاء الجدول مباشرة 
CREATE TABLE Orders (
    order_id INT PRIMARY KEY,
    item VARCHAR(40),
    amount INT,
    customer_id INT REFERENCES Customers(id)
);
GO

