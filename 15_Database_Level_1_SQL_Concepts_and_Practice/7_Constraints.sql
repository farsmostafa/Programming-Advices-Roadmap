-- ==============================================================================
-- 1. القيود
-- SQL Constraints
-- ==============================================================================
-- الوصف: تستخدم القيود لتحديد القواعد التي تحكم البيانات داخل الجدول
-- الهدف منها تقييد نوع البيانات المسموح إدخالها لضمان دقة وموثوقية قاعدة البيانات
-- إذا حدث أي تعارض أو انتهاك للقيد أثناء إدخال أو تعديل البيانات، يتم إلغاء العملية فورا
-- Aborted
-- يمكن تطبيق القيود على مستوى العمود الواحد فقط أو على مستوى الجدول بالكامل
-- Column level or Table level

-- متى يتم إنشاء القيود؟
-- يمكن إضافتها أثناء بناء الجدول باستخدام أمر
-- CREATE TABLE
-- أو بعد إنشاء الجدول باستخدام أمر التعديل
-- ALTER TABLE

-- الصيغة العامة لإضافة القيود أثناء بناء الجدول:
/*
CREATE TABLE table_name (
    column1 datatype constraint,
    column2 datatype constraint,
    column3 datatype constraint,
    ....
);
*/

-- ==============================================================================
-- القائمة الأساسية للقيود (سيتم تفصيلها برمجيا في الدروس القادمة)
-- ==============================================================================

-- 1. يضمن عدم قبول العمود لأي قيم فارغة إطلاقا
-- NOT NULL

-- 2. يضمن أن جميع القيم داخل العمود فريدة تماما وغير مكررة
-- UNIQUE

-- 3. يجمع بين القيدين السابقين لتمييز كل صف في الجدول بشكل فريد ولا يقبل التكرار أو الفراغ
-- PRIMARY KEY

-- 4. يمنع أي عمليات قد تدمر الروابط والعلاقات المعمارية بين الجداول
-- FOREIGN KEY

-- 5. يضمن أن القيم المدخلة في العمود تلبي شرطا منطقيا أو رياضيا محددا
-- CHECK

-- 6. يضع قيمة افتراضية للعمود في حال لم يقم المستخدم بتمرير أي قيمة أثناء الإدخال
-- DEFAULT

-- 7. يستخدم لإنشاء الفهارس لتسريع عمليات البحث واسترجاع البيانات بشكل كبير جدا
-- CREATE INDEX
GO



-- ==============================================================================
-- 2. المفتاح الأساسي
-- PRIMARY KEY Constraint
-- ==============================================================================
-- الوصف: يستخدم هذا القيد لتمييز كل سجل في الجدول بشكل فريد
-- القيم المدخلة في هذا الحقل يجب أن تكون فريدة ولا تقبل القيم الفارغة إطلاقا
-- UNIQUE / NOT NULL
-- يمكن أن يحتوي الجدول على مفتاح أساسي واحد فقط
-- يمكن أن يتكون هذا المفتاح من عمود واحد، أو من دمج عدة أعمدة معا ويسمى حينها مفتاح مركب
-- Composite Key

-- ==============================================================================
-- أمثلة الإنشاء مع بناء الجدول
-- CREATE TABLE
-- ==============================================================================

-- الطريقة الأولى: إنشاء المفتاح الأساسي على عمود واحد بشكل مباشر
CREATE TABLE Persons_Simple (
    ID INT NOT NULL PRIMARY KEY,
    LastName VARCHAR(255) NOT NULL,
    FirstName VARCHAR(255),
    Age INT
);
GO

-- الطريقة الثانية: تسمية القيد برمجيا وإنشاء مفتاح أساسي مركب من عمودين
-- القيد هنا يمثل مفتاحا أساسيا واحدا، لكن قيمته تتكون من دمج عمودي المعرف والاسم الأخير
-- PK_Person
CREATE TABLE Persons_Composite (
    ID INT NOT NULL,
    LastName VARCHAR(255) NOT NULL,
    FirstName VARCHAR(255),
    Age INT,
    CONSTRAINT PK_Person PRIMARY KEY (ID, LastName)
);
GO

-- ==============================================================================
-- أمثلة الإضافة والتعديل والحذف
-- ALTER TABLE / DROP CONSTRAINT
-- ==============================================================================
-- ملاحظة هندسية: عند إضافة مفتاح أساسي لجدول موجود، يجب أن تكون الأعمدة المستهدفة
-- معرفة مسبقا بأنها لا تقبل القيم الفارغة
-- NOT NULL

-- تجهيز جدول للاختبار بدون مفتاح أساسي
CREATE TABLE Persons_Alter (
    ID INT NOT NULL,
    LastName VARCHAR(255) NOT NULL
);
GO

-- الطريقة الثالثة: إضافة المفتاح الأساسي لجدول موجود مسبقا
-- كود إضافة مفتاح لعمود واحد بدون تسمية (مكتوب كتعليق للتوضيح فقط)
/*
ALTER TABLE Persons_Alter
ADD PRIMARY KEY (ID);
*/

-- كود إضافة مفتاح مركب مع تسمية القيد صراحة (يُفضل هندسيا لسهولة حذفه لاحقا)
ALTER TABLE Persons_Alter
ADD CONSTRAINT PK_Person_Alter PRIMARY KEY (ID, LastName);
GO

-- الطريقة الرابعة: حذف قيد المفتاح الأساسي
-- يتم الحذف باستخدام اسم القيد الذي قمنا بتعريفه في الخطوة السابقة
ALTER TABLE Persons_Alter
DROP CONSTRAINT PK_Person_Alter;
GO


-- ==============================================================================
-- 3. المفتاح الأجنبي
-- FOREIGN KEY Constraint
-- ==============================================================================
-- الوصف: يستخدم هذا القيد لمنع الإجراءات التي قد تدمر الروابط والعلاقات المعمارية بين الجداول
-- المفتاح الأجنبي هو حقل أو مجموعة حقول في جدول معين يشير إلى المفتاح الأساسي في جدول آخر
-- PRIMARY KEY

-- ==============================================================================
-- أمثلة الإنشاء مع بناء الجدول
-- CREATE TABLE
-- ==============================================================================

-- الطريقة الأولى: إنشاء المفتاح الأجنبي بشكل مباشر وبدون تسمية صريحة للقيد
CREATE TABLE Orders_Simple (
    OrderID INT NOT NULL PRIMARY KEY,
    OrderNumber INT NOT NULL,
    PersonID INT FOREIGN KEY REFERENCES Persons(PersonID)
);
GO

-- الطريقة الثانية: تسمية القيد برمجيا
-- يعتبر هذا الأسلوب من أفضل الممارسات الهندسية لسهولة إدارة وحذف القيد لاحقا
-- FK_PersonOrder
CREATE TABLE Orders_Named (
    OrderID INT NOT NULL,
    OrderNumber INT NOT NULL,
    PersonID INT,
    PRIMARY KEY (OrderID),
    CONSTRAINT FK_PersonOrder FOREIGN KEY (PersonID) REFERENCES Persons(PersonID)
);
GO

-- ==============================================================================
-- أمثلة الإضافة والحذف لجدول موجود
-- ALTER TABLE / DROP CONSTRAINT
-- ==============================================================================

-- تجهيز جدول للاختبار بدون مفتاح أجنبي
CREATE TABLE Orders_Alter (
    OrderID INT NOT NULL PRIMARY KEY,
    OrderNumber INT NOT NULL,
    PersonID INT
);
GO

-- الطريقة الثالثة: إضافة المفتاح الأجنبي لجدول موجود مسبقا بدون تسمية
-- مكتوب كتعليق لتجنب التضارب مع الكود التالي
/*
ALTER TABLE Orders_Alter
ADD FOREIGN KEY (PersonID) REFERENCES Persons(PersonID);
*/
GO

-- الطريقة الرابعة: إضافة المفتاح الأجنبي مع تسمية القيد صراحة
ALTER TABLE Orders_Alter
ADD CONSTRAINT FK_PersonOrder_Alter 
FOREIGN KEY (PersonID) REFERENCES Persons(PersonID);
GO

-- الطريقة الخامسة: حذف قيد المفتاح الأجنبي
-- يتم الحذف فورا باستخدام اسم القيد الذي قمنا بتعريفه في الخطوة السابقة
ALTER TABLE Orders_Alter
DROP CONSTRAINT FK_PersonOrder_Alter;
GO


-- ==============================================================================
-- 4. قيد منع القيم الفارغة
-- NOT NULL Constraint
-- ==============================================================================
-- الوصف: يضمن هذا القيد عدم قبول العمود لأي قيم فارغة إطلاقا
-- في حال محاولة إدخال سجل جديد أو تحديثه دون تمرير قيمة لهذا العمود، سيتم رفض العملية فورا

-- ==============================================================================
-- أمثلة الإنشاء مع بناء الجدول
-- CREATE TABLE
-- ==============================================================================

-- إنشاء جدول مع تطبيق القيد على أعمدة المعرف والاسم الأخير والاسم الأول
-- بينما تم ترك عمود العمر بدون القيد ليسمح بالقيم الفارغة افتراضيا
CREATE TABLE Persons_NotNull (
    ID INT NOT NULL,
    LastName VARCHAR(255) NOT NULL,
    FirstName VARCHAR(255) NOT NULL,
    Age INT
);
GO

-- ==============================================================================
-- أمثلة الإضافة والتعديل لجدول موجود
-- ALTER TABLE
-- ==============================================================================

-- تعديل هيكل عمود العمر في الجدول الموجود مسبقا ليصبح إجباريا ولا يقبل القيم الفارغة
-- ملاحظة هندسية: لكي تنجح هذه العملية، يجب ألا يحتوي الجدول حاليا على أي سجلات تمتلك قيما فارغة في عمود العمر
ALTER TABLE Persons_NotNull
ALTER COLUMN Age INT NOT NULL;
GO


-- ==============================================================================
-- 5. القيد الافتراضي
-- DEFAULT Constraint
-- ==============================================================================
-- الوصف: يستخدم هذا القيد لتعيين قيمة افتراضية لعمود محدد
-- سيتم إدراج هذه القيمة الافتراضية تلقائيا في جميع السجلات الجديدة إذا لم يقم المبرمج بتمرير قيمة أخرى أثناء الإدخال
-- يمكن استخدامه لتعيين قيم ثابتة كنصوص وأرقام، أو لتوليد قيم نظامية ديناميكية باستخدام دوال مدمجة مثل
-- GETDATE()

-- ==============================================================================
-- أمثلة الإنشاء مع بناء الجدول
-- CREATE TABLE
-- ==============================================================================

-- الطريقة الأولى: تعيين نص ثابت كقيمة افتراضية 
CREATE TABLE Persons_Default (
    ID INT NOT NULL,
    LastName VARCHAR(255) NOT NULL,
    FirstName VARCHAR(255),
    Age INT,
    City VARCHAR(255) DEFAULT 'Amman'
);
GO

-- الطريقة الثانية: تعيين دالة نظامية كقيمة افتراضية (تاريخ ووقت النظام الحالي)
CREATE TABLE Orders_Default (
    ID INT NOT NULL,
    OrderNumber INT NOT NULL,
    OrderDate DATE DEFAULT GETDATE()
);
GO

-- ==============================================================================
-- أمثلة الإضافة والحذف لجدول موجود
-- ALTER TABLE / DROP CONSTRAINT
-- ==============================================================================

-- تجهيز جدول لاختبار عمليات التعديل
CREATE TABLE Persons_AlterDefault (
    ID INT NOT NULL,
    City VARCHAR(255)
);
GO

-- الطريقة الثالثة: إضافة القيد الافتراضي لجدول موجود مسبقا مع تسمية القيد صراحة
-- من الممارسات الهندسية الإلزامية تسمية القيود لتسهيل صيانتها وإدارتها لاحقا
-- df_City
ALTER TABLE Persons_AlterDefault
ADD CONSTRAINT df_City DEFAULT 'Amman' FOR City;
GO

-- الطريقة الرابعة: حذف القيد الافتراضي
-- يتم الحذف مباشرة باستخدام اسم القيد الذي قمنا بتعريفه في الخطوة السابقة
ALTER TABLE Persons_AlterDefault
DROP CONSTRAINT df_City;
GO


-- ==============================================================================
-- 6. قيد التحقق
-- CHECK Constraint
-- ==============================================================================
-- الوصف: يستخدم هذا القيد للحد من نطاق القيم التي يمكن إدخالها في عمود معين
-- يضمن القيد أن القيم المدخلة تلبي شرطا منطقيا أو رياضيا محددا
-- يمكن تطبيقه على مستوى عمود واحد، أو تطبيقه على مستوى الجدول بأكمله لتقييد القيم بناء على أعمدة أخرى في نفس الصف

-- ==============================================================================
-- أمثلة الإنشاء مع بناء الجدول
-- CREATE TABLE
-- ==============================================================================

-- الطريقة الأولى: إنشاء القيد على عمود واحد بشكل مباشر بدون تسمية صريحة
-- سيمنع هذا القيد إدخال أي موظف أو شخص يقل عمره عن 18 عاما
CREATE TABLE Persons_Check (
    ID INT NOT NULL,
    LastName VARCHAR(255) NOT NULL,
    FirstName VARCHAR(255),
    Age INT CHECK (Age >= 18)
);
GO

-- الطريقة الثانية: تسمية القيد صراحة وتطبيقه كشرط مركب على عدة أعمدة
-- يُعد هذا الأسلوب هو المعيار الهندسي الأفضل لسهولة تتبع الأخطاء وحذف القيد لاحقا
-- CHK_Person
CREATE TABLE Persons_CheckMulti (
    ID INT NOT NULL,
    LastName VARCHAR(255) NOT NULL,
    FirstName VARCHAR(255),
    Age INT,
    City VARCHAR(255),
    CONSTRAINT CHK_Person CHECK (Age >= 18 AND City = 'Amman')
);
GO

-- ==============================================================================
-- أمثلة الحذف لجدول موجود
-- DROP CONSTRAINT
-- ==============================================================================

-- الطريقة الثالثة: حذف قيد التحقق
-- يتم الحذف فورا باستخدام اسم القيد الذي قمنا بتعريفه في الخطوة السابقة دون الحاجة لتكرار الشرط
ALTER TABLE Persons_CheckMulti
DROP CONSTRAINT CHK_Person;
GO


-- ==============================================================================
-- 7. قيد القيم الفريدة
-- UNIQUE Constraint
-- ==============================================================================
-- الوصف: يضمن هذا القيد أن جميع القيم داخل العمود فريدة تماما وغير مكررة
-- كلا من القيد `UNIQUE` والمفتاح الأساسي `PRIMARY KEY` يضمنان عدم تكرار البيانات
-- المفتاح الأساسي يتضمن قيد `UNIQUE` بشكل تلقائي ضمن هيكلته
-- ملاحظة هندسية: يمكنك إضافة العديد من قيود `UNIQUE` في نفس الجدول، بينما يُسمح بمفتاح أساسي واحد فقط لكل جدول

-- ==============================================================================
-- أمثلة الإنشاء مع بناء الجدول
-- CREATE TABLE
-- ==============================================================================

-- الطريقة الأولى: إنشاء القيد على عمود واحد بشكل مباشر بدون تسمية صريحة
CREATE TABLE Persons_Unique (
    ID INT NOT NULL UNIQUE,
    LastName VARCHAR(255) NOT NULL,
    FirstName VARCHAR(255),
    Age INT
);
GO

-- الطريقة الثانية: تسمية القيد صراحة وتطبيقه على عدة أعمدة
-- يتم استخدام هذه الطريقة لضمان عدم تكرار التركيبة المكونة من المعرف والاسم الأخير معاً
-- `UC_Person`
CREATE TABLE Persons_UniqueMulti (
    ID INT NOT NULL,
    LastName VARCHAR(255) NOT NULL,
    FirstName VARCHAR(255),
    Age INT,
    CONSTRAINT UC_Person UNIQUE (ID, LastName)
);
GO

-- ==============================================================================
-- أمثلة الإضافة والحذف لجدول موجود
-- ALTER TABLE / DROP CONSTRAINT
-- ==============================================================================

-- تجهيز جدول لاختبار عمليات التعديل
CREATE TABLE Persons_AlterUnique (
    ID INT NOT NULL,
    LastName VARCHAR(255) NOT NULL
);
GO

-- الطريقة الثالثة: إضافة القيد لعمود واحد في جدول موجود مسبقاً (بدون تسمية صريحة)
-- مكتوب كتعليق لتجنب التضارب مع الكود التالي
/*
ALTER TABLE Persons_AlterUnique
ADD UNIQUE (ID);
*/
GO

-- الطريقة الرابعة: إضافة القيد لعدة أعمدة مع تسمية القيد صراحة (الممارسة الهندسية الأفضل)
ALTER TABLE Persons_AlterUnique
ADD CONSTRAINT UC_Person_Alter UNIQUE (ID, LastName);
GO

-- الطريقة الخامسة: حذف قيد القيم الفريدة
-- يتم الحذف مباشرة باستخدام اسم القيد الذي قمنا بتعريفه في الخطوة السابقة
ALTER TABLE Persons_AlterUnique
DROP CONSTRAINT UC_Person_Alter;
GO


