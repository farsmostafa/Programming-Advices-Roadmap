-- 8. الفهارس
-- SQL Index
-- ==============================================================================
-- الوصف: تستخدم الفهارس لتسريع استرجاع البيانات من قاعدة البيانات بشكل ملحوظ
-- الفهارس تعمل في الخلفية ولا يراها المستخدم نهائيا، هدفها الوحيد تحسين أداء الاستعلامات
--
-- ملاحظة هندسية (Performance Cost): تحديث الجداول التي تحتوي على فهارس (إضافة، تعديل، حذف) 
-- يستغرق وقتا أطول من الجداول العادية لأن السيرفر يضطر لتحديث الفهرس مع كل تغيير.
-- بناء على ذلك كأفضل ممارسة: قم بإنشاء الفهارس فقط على الأعمدة التي تتعرض لعمليات بحث مكثفة.

-- ==============================================================================
-- أمثلة الإنشاء
-- CREATE INDEX
-- ==============================================================================

-- 1. إنشاء فهرس عادي على عمود واحد (يسمح بتكرار القيم بشكل طبيعي)
-- idx_lastname
CREATE INDEX idx_lastname
ON Persons (LastName);
GO

-- 2. إنشاء فهرس مركب على أكثر من عمود لتسريع الاستعلامات التي تبحث بهما معا
-- يتم الفصل بين أسماء الأعمدة بفاصلة
-- idx_pname
CREATE INDEX idx_pname
ON Persons (LastName, FirstName);
GO

-- 3. إنشاء فهرس فريد (يمنع تكرار القيم تماما داخل الأعمدة المفهرسة)
-- UNIQUE INDEX
CREATE UNIQUE INDEX idx_unique_lastname
ON Persons (LastName);
GO

-- ==============================================================================
-- أمثلة الحذف
-- DROP INDEX
-- ==============================================================================

-- 4. حذف الفهرس من الجدول
-- الصيغة المتبعة تتطلب ذكر اسم الجدول ثم نقطة ثم اسم الفهرس
DROP INDEX Persons.idx_lastname;
GO

-- ==============================================================================
-- ملاحظة معمارية متقدمة: الفهارس العنقودية والمفاتيح الأساسية
-- Clustered Index & Primary Key
-- ==============================================================================
-- عند إنشاء قيد مفتاح أساسي 
-- PRIMARY KEY
-- يقوم محرك قاعدة البيانات تلقائيا بإنشاء فهرس عنقودي
-- Clustered Index
-- متصل بأعمدة هذا المفتاح. 
-- الفهرس العنقودي يقوم بترتيب السجلات فيزيائيا على القرص الصلب بناء على هذا المفتاح، 
-- مما يجعله أسرع بكثير جدا من الفهارس العادية
-- Normal Indexes
-- ملاحظة: لا يمكن أن يحتوي الجدول إلا على فهرس عنقودي واحد فقط.


