-- ==============================================================================
-- 1. الجداول الوهمية (العروض)
-- Views
-- ==============================================================================
-- الوصف: العرض هو عبارة عن جدول وهمي مبني على نتيجة استعلام برمجي
-- Virtual Table
-- يحتوي على صفوف وأعمدة تماما مثل الجداول الحقيقية، وتأتي بياناته من جدول واحد أو أكثر
-- يمكنك دمج استعلامات ودوال معقدة داخل العرض لتقديم البيانات للمستخدم وكأنها قادمة من جدول واحد
-- يتم إنشاء العرض باستخدام الأمر
-- CREATE VIEW
-- ملاحظة هندسية هامة: العرض يعرض دائما بيانات محدثة لحظيا
-- Up-to-date data
-- حيث يقوم محرك قاعدة البيانات بتنفيذ الاستعلام الداخلي وإعادة بناء العرض في كل مرة يتم استدعاؤه

-- الصيغة العامة:
-- CREATE VIEW view_name AS SELECT column1, column2 FROM table_name WHERE condition;

-- ==============================================================================
-- أمثلة عملية
-- ==============================================================================

-- 1. إنشاء عرض يدمج بيانات الموظفين مع أسماء الأقسام لتسهيل الاستعلام لاحقا
CREATE VIEW vw_EmployeeDetails AS
SELECT Employees.ID, 
       Employees.FirstName, 
       Employees.LastName, 
       Departments.Name AS DepartmentName
FROM Employees
INNER JOIN Departments 
ON Employees.DepartmentID = Departments.ID;
GO

-- 2. بمجرد إنشاء العرض، يمكنك الاستعلام عنه وكأنه جدول حقيقي تماما
SELECT * FROM vw_EmployeeDetails;
GO

-- 3. يمكنك أيضا تطبيق جمل شرطية على العرض نفسه أثناء الاستعلام
SELECT * FROM vw_EmployeeDetails
WHERE DepartmentName = 'IT';
GO


-- ==============================================================================
-- 2. معامل التحقق من الوجود
-- EXISTS Operator
-- ==============================================================================
-- الوصف: يستخدم هذا المعامل لاختبار وجود أي سجلات تتطابق مع شرط معين داخل استعلام فرعي
-- Subquery
-- يرجع هذا المعامل النتيجة صحيحة إذا أعاد الاستعلام الفرعي سجلا واحدا أو أكثر
-- TRUE
-- سيتم تنفيذ الاستعلام الخارجي فقط إذا لم تكن نتيجة الاستعلام الفرعي فارغة
-- NULL / Empty Result-set

-- الصيغة العامة:
-- SELECT columns FROM table_name WHERE EXISTS (SELECT column_name FROM table_name WHERE condition);

-- ==============================================================================
-- أمثلة عملية ومراحل تحسين الأداء 
-- Optimization
-- ==============================================================================

-- 1. اختبار بسيط: إرجاع كلمة (yes) إذا كان هناك طلب للعميل رقم 3 بقيمة أقل من 600
SELECT X = 'yes' 
WHERE EXISTS ( 
    SELECT * FROM Orders 
    WHERE customerID = 3 AND Amount < 600 
);

-- 2. استعلام متداخل: استرجاع بيانات العملاء الذين لديهم طلبات بقيمة أقل من 600
-- Correlated Subquery
SELECT * FROM Customers T1 
WHERE EXISTS ( 
    SELECT * FROM Orders 
    WHERE customerID = T1.CustomerID AND Amount < 600 
);

-- 3. أداء أفضل: إخبار السيرفر بالتوقف عن البحث بمجرد إيجاد أول سجل يطابق الشرط
-- More optimized
SELECT * FROM Customers T1 
WHERE EXISTS ( 
    SELECT TOP 1 * FROM Orders 
    WHERE customerID = T1.CustomerID AND Amount < 600 
);

-- 4. الأداء الأمثل والأسرع: استرجاع حرف ثابت بدلا من جلب بيانات الأعمدة بالكامل في الاستعلام الفرعي
-- Fastest Performance
SELECT * FROM Customers T1 
WHERE EXISTS ( 
    SELECT TOP 1 R = 'Y' FROM Orders 
    WHERE customerID = T1.CustomerID AND Amount < 600 
);
GO


-- ==============================================================================
-- 3. دمج النتائج
-- UNION & UNION ALL Operators
-- ==============================================================================
-- الوصف: يستخدم هذا المعامل لدمج نتائج استعلامين أو أكثر في جدول نتائج واحد
-- UNION
-- شروط الاستخدام الإجبارية لنجاح الدمج:
-- 1. يجب أن يحتوي كل استعلام على نفس عدد الأعمدة
-- 2. يجب أن تكون أنواع البيانات في الأعمدة المتقابلة متوافقة
-- 3. يجب أن تكون الأعمدة بنفس الترتيب في جميع الاستعلامات المدمجة

-- بشكل افتراضي، يقوم هذا المعامل بدمج البيانات مع إزالة السجلات المكررة (استرجاع القيم الفريدة فقط)
-- DISTINCT
-- للسماح بتكرار البيانات ودمج جميع السجلات كما هي تماما، نستخدم
-- UNION ALL
-- ملاحظة هندسية: أسماء الأعمدة في النتيجة النهائية يتم تحديدها دائما بناء على أسماء الأعمدة في الاستعلام الأول

-- الصيغة العامة:
-- SELECT columns FROM table1 UNION SELECT columns FROM table2;

-- ==============================================================================
-- أمثلة عملية
-- ==============================================================================

-- استعراض بيانات الموظفين النشطين والمستقيلين كل على حدة
SELECT * FROM ActiveEmployees;
SELECT * FROM ResignedEmployees;
GO

-- دمج بيانات الموظفين النشطين والمستقيلين في قائمة (جدول نتائج) واحدة
SELECT * FROM ActiveEmployees
UNION
SELECT * FROM ResignedEmployees;
GO

-- دمج نفس الجدول مع نفسه لتوضيح السلوك الافتراضي لمعامل الدمج
-- سيقوم هذا الاستعلام بحذف أي تكرار واسترجاع السجلات الفريدة فقط للقسم
SELECT * FROM Departments
UNION 
SELECT * FROM Departments;
GO

-- دمج نفس الجدول مع نفسه باستخدام معامل الدمج الشامل
-- UNION ALL
-- سيقوم هذا الاستعلام بإرفاق البيانات كما هي بغض النظر عن التكرار (ستظهر السجلات مضاعفة)
SELECT * FROM Departments
UNION ALL
SELECT * FROM Departments;
GO
