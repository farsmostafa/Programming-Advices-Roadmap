-- ==============================================================================
-- SQL Data Definition Language (DDL) & Backup Reference 
-- ==============================================================================

-- ------------------------------------------------------------------------------
-- 1. Create Database
-- الوصف: إنشاء قاعدة بيانات جديدة فارغة في السيرفر.
-- Syntax: CREATE DATABASE [DatabaseName];
-- ------------------------------------------------------------------------------
CREATE DATABASE TestDB;
GO

-- ------------------------------------------------------------------------------
-- 2. Create Database IF NOT EXISTS
-- الوصف: التحقق من عدم وجود قاعدة البيانات قبل إنشائها لتجنب توقف الكود بخطأ (Error).
-- Syntax: IF NOT EXISTS (SELECT * FROM sys.databases WHERE name = 'DatabaseName') BEGIN CREATE DATABASE [DatabaseName] END;
-- ------------------------------------------------------------------------------
IF NOT EXISTS (SELECT * FROM sys.databases WHERE name = 'CompanyDB')
BEGIN
    CREATE DATABASE CompanyDB;
END
GO

-- ------------------------------------------------------------------------------
-- 3. Switch Database
-- الوصف: تحديد قاعدة البيانات التي سيتم تنفيذ الاستعلامات (Queries) القادمة عليها.
-- Syntax: USE [DatabaseName];
-- ------------------------------------------------------------------------------
USE CompanyDB;
GO

-- ------------------------------------------------------------------------------
-- 4. Drop Database
-- الوصف: حذف قاعدة البيانات بالكامل بجميع جداولها وبياناتها (إجراء لا يمكن التراجع عنه).
-- Syntax: DROP DATABASE [DatabaseName];
-- ------------------------------------------------------------------------------
-- DROP DATABASE TestDB; 
GO

-- ------------------------------------------------------------------------------
-- 5. Drop Database IF EXISTS
-- الوصف: حذف قاعدة البيانات فقط في حالة وجودها فعلياً لتجنب الأخطاء (مدعوم في إصدارات 2016+).
-- Syntax: DROP DATABASE IF EXISTS [DatabaseName];
-- ------------------------------------------------------------------------------
DROP DATABASE IF EXISTS TestDB;
GO

-- ------------------------------------------------------------------------------
-- 6. SQL DataTypes (أهم أنواع البيانات)
-- الوصف: تحديد نوع البيانات وحجمها داخل الأعمدة.
-- أنواع شائعة:
-- INT             : أرقام صحيحة
-- DECIMAL(18,2)   : أرقام عشرية (18 رقم إجمالي، منها 2 بعد الفاصلة)
-- NVARCHAR(100)   : نصوص تقبل الحروف العربية والإنجليزية (طول متغير حتى 100 حرف)
-- BIT             : قيم منطقية (0 أو 1 / True أو False)
-- DATETIME        : تاريخ ووقت
-- ------------------------------------------------------------------------------

-- ------------------------------------------------------------------------------
-- 7. Create Table
-- الوصف: بناء هيكل جدول جديد داخل قاعدة البيانات المحددة.
-- Syntax: CREATE TABLE [TableName] ( [ColumnName] DataType Constraints, ... );
-- ------------------------------------------------------------------------------
CREATE TABLE Employees (
    EmployeeID INT PRIMARY KEY IDENTITY(1,1),
    FullName NVARCHAR(100) NOT NULL,
    Salary DECIMAL(10,2),
    IsActive BIT DEFAULT 1,
    HireDate DATETIME DEFAULT GETDATE()
);
GO

-- ------------------------------------------------------------------------------
-- 8. Drop Table
-- الوصف: حذف الجدول بالكامل بجميع بياناته وهيكله.
-- Syntax: DROP TABLE [TableName];
-- ------------------------------------------------------------------------------
 DROP TABLE Employees;
GO

-- ==============================================================================
-- DDL - Alter Table Statement (تعديل هياكل الجداول)
-- ==============================================================================

-- ------------------------------------------------------------------------------
-- 9. Add Column
-- الوصف: إضافة عمود جديد إلى جدول موجود مسبقاً.
-- Syntax: ALTER TABLE [TableName] ADD [ColumnName] DataType;
-- ------------------------------------------------------------------------------
ALTER TABLE Employees 
ADD DateOfBirth DATE;
GO

-- ------------------------------------------------------------------------------
-- 10. Modify a column
-- الوصف: تعديل نوع البيانات لعمود موجود (يجب توافق البيانات القديمة مع النوع الجديد).
-- Syntax: ALTER TABLE [TableName] ALTER COLUMN [ColumnName] NewDataType;
-- ------------------------------------------------------------------------------
ALTER TABLE Employees 
ALTER COLUMN FullName NVARCHAR(200) NOT NULL;
GO

-- ------------------------------------------------------------------------------
-- 11. Rename Column
-- الوصف: تغيير اسم عمود موجود. في SQL Server يُمنع استخدام ALTER لهذا الغرض، نستخدم الإجراء المخزن (sp_rename).
-- Syntax: EXEC sp_rename 'TableName.OldColumnName', 'NewColumnName', 'COLUMN';
-- ------------------------------------------------------------------------------
EXEC sp_rename 'Employees.FullName', 'EmployeeName', 'COLUMN';
GO

-- ------------------------------------------------------------------------------
-- 12. Rename a table
-- الوصف: تغيير اسم الجدول بالكامل باستخدام الإجراء المخزن.
-- Syntax: EXEC sp_rename 'OldTableName', 'NewTableName';
-- ------------------------------------------------------------------------------
EXEC sp_rename 'Employees', 'Staff';
GO

-- ------------------------------------------------------------------------------
-- 13. Delete a column (Drop Column)
-- الوصف: حذف عمود ببياناته من الجدول.
-- Syntax: ALTER TABLE [TableName] DROP COLUMN [ColumnName];
-- ------------------------------------------------------------------------------
ALTER TABLE Staff 
DROP COLUMN DateOfBirth;
GO

-- ==============================================================================
-- Backup & Restore Database
-- ==============================================================================

-- ------------------------------------------------------------------------------
-- 14. Backup Database (Full Backup)
-- الوصف: أخذ نسخة احتياطية كاملة من قاعدة البيانات وحفظها في المسار المحدد.
-- Syntax: BACKUP DATABASE [DatabaseName] TO DISK = 'FilePath.bak';
-- ------------------------------------------------------------------------------
BACKUP DATABASE CompanyDB 
TO DISK = 'C:\Backups\CompanyDB_Full.bak';
GO

-- ------------------------------------------------------------------------------
-- 15. Differential Backup
-- الوصف: أخذ نسخة احتياطية سريعة وخفيفة تحتوي فقط على التغييرات التي حدثت منذ آخر Full Backup.
-- Syntax: BACKUP DATABASE [DatabaseName] TO DISK = 'FilePath.bak' WITH DIFFERENTIAL;
-- ------------------------------------------------------------------------------
BACKUP DATABASE CompanyDB 
TO DISK = 'C:\Backups\CompanyDB_Diff.bak' 
WITH DIFFERENTIAL;
GO

-- ------------------------------------------------------------------------------
-- 16. Restore Database
-- الوصف: استعادة قاعدة البيانات من ملف النسخة الاحتياطية. (يجب ألا تكون قاعدة البيانات قيد الاستخدام أثناء الاستعادة).
-- Syntax: RESTORE DATABASE [DatabaseName] FROM DISK = 'FilePath.bak';
-- ------------------------------------------------------------------------------
USE master; -- يجب الخروج من قاعدة البيانات قبل استعادتها
GO

RESTORE DATABASE CompanyDB 
FROM DISK = 'C:\Backups\CompanyDB_Full.bak' 
WITH REPLACE; -- WITH REPLACE تجبر السيرفر على الكتابة فوق القاعدة الحالية إن وجدت
GO